# '{' and '}' are not glyphs: they delimit control codes in script text.


def rows(ch):
    """9 ints (5-bit rows, bit 4 = left pixel) for one character."""
    g = G[ch]
    return [int(r.replace('#', '1').replace('.', '0') or '0', 2) for r in g] + [0] * (9 - len(g))


def cell(pair):
    """24-byte font cell for two characters (game format: 12 big-endian 16-bit rows, bit 15 = left)."""
    a, b = pair
    out = bytearray(24)
    for r, (ra, rb) in enumerate(zip(rows(a), rows(b))):
        w = ra << 11 | rb << 5  # left glyph in px 0-4, right glyph in px 6-10
        out[(r + TOP) * 2:(r + TOP) * 2 + 2] = w.to_bytes(2, 'big')
    return bytes(out)


def selftest():
    for ch, g in G.items():
        assert len(g) <= 9, ch
        assert all(len(r) == WIDTH for r in g if r), f'{ch!r}: rows must be {WIDTH} px wide or empty'
    printable = {chr(c) for c in range(0x20, 0x7F)} - {'{', '}'}
    assert printable <= set(G), sorted(printable - set(G))
    c = cell('AB')
    assert c[TOP * 2:TOP * 2 + 2] == bytes([0b01110011, 0b11000000]), c.hex()  # .###. gap ####.
    assert cell('  ') == bytes(24)
    print(f'font_en selftest ok: {len(G)} glyphs')


def sheet(path):
    import struct
    import zlib
    chars = sorted(G)
    pairs = [''.join(chars[i:i + 2]).ljust(2) for i in range(0, len(chars), 2)]
    cols, z = 16, 3
    W, H = cols * 13 * z, ((len(pairs) + cols - 1) // cols) * 13 * z
    px = bytearray(W * H)
    for i, p in enumerate(pairs):
        c = cell(p)
        for r in range(12):
            w = int.from_bytes(c[r * 2:r * 2 + 2], 'big')
            for x in range(12):
                if w >> (15 - x) & 1:
                    for dy in range(z):
                        for dx in range(z):
                            px[((i // cols) * 13 * z + r * z + dy) * W + (i % cols) * 13 * z + x * z + dx] = 255
    raw = b''.join(b'\0' + bytes(px[y * W:(y + 1) * W]) for y in range(H))
    chunk = lambda t, d: struct.pack('>I', len(d)) + t + d + struct.pack('>I', zlib.crc32(t + d))  # noqa: E731
    with open(path, 'wb') as f:
        f.write(b'\x89PNG\r\n\x1a\n' + chunk(b'IHDR', struct.pack('>IIBBBBB', W, H, 8, 0, 0, 0, 0))
                + chunk(b'IDAT', zlib.compress(raw)) + chunk(b'IEND', b''))


